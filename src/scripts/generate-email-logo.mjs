#!/usr/bin/env node
/**
 * Writes `lib/email/logo.ts` from `public/img/brand/logo.png`.
 *
 * Mail clients cannot fetch from the site: there is no custom domain yet, and
 * a remote image would be blocked by default anyway. The logo therefore
 * travels with the message as an inline CID attachment, which means the bytes
 * have to be reachable from server code — not from `public/`, which is served
 * by the CDN and is not part of the serverless bundle. Embedding them as a
 * base64 constant is the one form that survives any deployment target.
 *
 * The source artwork is 1440px wide and far too heavy to attach to every
 * enquiry, so it is trimmed of its transparent margin and resized to twice its
 * display width. `--check` (wired into `npm run verify`) fails if the artwork
 * has changed without this being regenerated.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { PROPERTY } from "../configuration/property.mjs";
import sharp from "sharp";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(ROOT, "public", "img", "brand", "logo.png");
const OUTPUT = join(ROOT, "lib", "email", "logo.ts");

/** Rendered width in the email; the bitmap is twice this for retina screens. */
const DISPLAY_WIDTH = 190;

async function render() {
  const source = readFileSync(SOURCE);

  const resized = await sharp(source)
    // The artwork carries a wide transparent margin that would otherwise eat
    // the header's padding.
    .trim()
    .resize({ width: DISPLAY_WIDTH * 2, withoutEnlargement: true })
    // A palette PNG is a third of the size here and the artwork is flat colour,
    // so nothing is visibly lost.
    .png({ palette: true, quality: 90, compressionLevel: 9 })
    .toBuffer();

  const { width, height } = await sharp(resized).metadata();
  const displayHeight = Math.round((height / width) * DISPLAY_WIDTH);
  const sourceHash = createHash("sha256").update(source).digest("hex").slice(0, 12);

  return `/* Generated by scripts/generate-email-logo.mjs — do not edit.
   Source: public/img/brand/logo.png (sha256 ${sourceHash})
   Replace the artwork and run \`npm run gen:email-logo\`. */

/** Attached inline and referenced as \`cid:\${EMAIL_LOGO_CID}\` by the layout. */
export const EMAIL_LOGO_CID = "brand-logo";

export const EMAIL_LOGO_FILENAME = "${PROPERTY.brand.slug}.png";

/** Rendered size in CSS pixels; the bitmap behind it is twice as wide. */
export const EMAIL_LOGO_WIDTH = ${DISPLAY_WIDTH};
export const EMAIL_LOGO_HEIGHT = ${displayHeight};

export const EMAIL_LOGO_BASE64 =
  "${resized.toString("base64")}";
`;
}

const expected = await render();

if (process.argv.includes("--check")) {
  let actual = "";
  try {
    actual = readFileSync(OUTPUT, "utf8");
  } catch {
    actual = "";
  }

  if (actual !== expected) {
    console.error(
      "✖ lib/email/logo.ts is out of date — run 'npm run gen:email-logo'."
    );
    process.exit(1);
  }

  console.log("✓ lib/email/logo.ts matches public/img/brand/logo.png");
} else {
  writeFileSync(OUTPUT, expected, "utf8");
  const kb = (Buffer.from(expected).length / 1024).toFixed(1);
  console.log(`✓ wrote lib/email/logo.ts (${kb} kB module)`);
}
